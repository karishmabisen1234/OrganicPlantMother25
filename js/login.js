    // FORM SWITCH
    function showForm(id) {
      document.querySelectorAll('.form').forEach(f => f.classList.remove('active'));
      document.getElementById(id).classList.add('active');
    }

    // PASSWORD TOGGLE
    function togglePassword(id, el) {
      const input = document.getElementById(id);
      if (input.type === "password") {
        input.type = "text";
        el.textContent = "🙈";
      } else {
        input.type = "password";
        el.textContent = "👁️";
      }
    }

    // ALERT
    function showAlert(id, msg, type) {
      const el = document.getElementById(id);
      el.textContent = msg;
      el.className = `alert ${type}`;
      el.style.display = "block";
      setTimeout(() => el.style.display = "none", 3000);
    }

    // STORAGE HANDLERS
    function getUsers() {
      return JSON.parse(localStorage.getItem('users')) || {};
    }

    function saveUsers(users) {
      localStorage.setItem('users', JSON.stringify(users));
    }

    // REGISTER
    function register() {
      const user = document.getElementById('newUser').value.trim().toLowerCase();
      const pass = document.getElementById('newPass').value.trim();
      if (!user || !pass) return showAlert('registerAlert', '⚠️ Fill all fields!', 'error');

      let users = getUsers();
      if (users[user]) return showAlert('registerAlert', '⚠️ Username already exists!', 'error');

      users[user] = pass;
      saveUsers(users);
      showAlert('registerAlert', '✅ Account created successfully!', 'success');
      setTimeout(() => showForm('loginForm'), 1500);
    }

    // LOGIN
    function login() {
      const user = document.getElementById('username').value.trim().toLowerCase();
      const pass = document.getElementById('password').value.trim();
      let users = getUsers();

      if (!users[user]) return showAlert('loginAlert', '❌ Invalid username or password!', 'error');
      if (users[user] !== pass) return showAlert('loginAlert', '❌ Invalid username or password!', 'error');

      sessionStorage.setItem("isLoggedIn", "true");
      sessionStorage.setItem("username", user);
      showAlert('loginAlert', '✅ Login successful! Redirecting...', 'success');
      setTimeout(() => window.location.href = "dashboard.html", 1500);
    }

    // RESET PASSWORD
    function resetPassword() {
      const user = document.getElementById('resetUser').value.trim().toLowerCase();
      const pass = document.getElementById('resetPass').value.trim();
      let users = getUsers();

      if (!users[user]) return showAlert('resetAlert', '⚠️ Username not found!', 'error');

      users[user] = pass;
      saveUsers(users);
      showAlert('resetAlert', '🔓 Password reset successfully!', 'success');
      setTimeout(() => showForm('loginForm'), 1500);
    }
